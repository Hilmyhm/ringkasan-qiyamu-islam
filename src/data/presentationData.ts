export function getUnitNumberForSlide(slideIndex: number): number | null {
  if (slideIndex === 1) return 1;
  if (slideIndex === 2) return 2;
  if (slideIndex >= 3 && slideIndex <= 7) return 3;
  if (slideIndex === 8) return 4;
  if (slideIndex === 9) return 5;
  if (slideIndex === 10) return 6;
  if (slideIndex === 11) return 7;
  return null;
}

